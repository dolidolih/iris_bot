def _find_mountain(name: str):
    """이름으로 산 검색. 결과: [(표시이름, (lat, lon, ele)), ...]"""
    name = name.strip()
    if name in MOUNTAIN_COORDS:
        return [(name, MOUNTAIN_COORDS[name])]
    base_matches = [
        (k, v) for k, v in MOUNTAIN_COORDS.items()
        if k == name or k.startswith(name + " (")
    ]
    if base_matches:
        return base_matches
    partial = [(k, v) for k, v in MOUNTAIN_COORDS.items() if name in k]
    return partial


def get_weather_message(mountain_name: str) -> str:
    matches = _find_mountain(mountain_name)
    if not matches:
        return (
            f"⚠️ '{mountain_name}' 정보가 없습니다.\n"
            "산 이름을 확인해주세요.\n"
            "예시: !날씨 북한산  /  !날씨 지리산  /  !날씨 한라산"
        )
    if len(matches) > 1:
        top = sorted(matches, key=lambda x: -x[1][2])[:10]
        out = [f"⚠️ '{mountain_name}'이(가) 여러 곳에 있어요.", ""]
        for mname, (_, _, ele) in top:
            out.append(f"  ⛰️ {mname} ({ele}m)")
        if len(matches) > 10:
            out.append(f"  ... 외 {len(matches)-10}개")
        out.append("")
        out.append("지역명을 포함해서 입력해주세요.")
        out.append(f"예시: !날씨 {top[0][0]}")
        return "\n".join(out)
    name, (lat, lon, ele) = matches[0]
    url = (
        "https://api.open-meteo.com/v1/forecast"
        f"?latitude={lat}&longitude={lon}"
        "&daily=weathercode,temperature_2m_max,temperature_2m_min"
        ",precipitation_probability_max,windspeed_10m_max"
        "&timezone=Asia%2FSeoul&forecast_days=3"
    )
    try:
        resp = requests.get(url, timeout=5)
        resp.raise_for_status()
        data = resp.json()
    except Exception as e:
        return f"날씨 조회 실패: {e}"
    daily  = data.get("daily", {})
    times  = daily.get("time", [])
    wcodes = daily.get("weathercode", [])
    max_t  = daily.get("temperature_2m_max", [])
    min_t  = daily.get("temperature_2m_min", [])
    rain_p = daily.get("precipitation_probability_max", [])
    wind   = daily.get("windspeed_10m_max", [])
    day_labels = {0: "오늘", 1: "내일", 2: "모레"}
    out = [f"[오름봇] ⛰️ {name} ({ele}m) 날씨", ""]
    for i, t in enumerate(times[:3]):
        label = day_labels.get(i, t)
        wc  = wcodes[i] if i < len(wcodes) else 0
        mx  = max_t[i]  if i < len(max_t)  else "-"
        mn  = min_t[i]  if i < len(min_t)  else "-"
        rp  = rain_p[i] if i < len(rain_p) else "-"
        ws  = wind[i]   if i < len(wind)   else "-"
        desc = WMO_CODES.get(wc, f"코드{wc}")
        out.append(f"📅 {label} ({t})")
        out.append(f"  {desc}")
        out.append(f"  🌡 {mn:.0f}°C ~ {mx:.0f}°C")
        out.append(f"  ☔ 강수확률 {rp:.0f}%  💨 최대 {ws:.0f}km/h")
        if i < 2:
            out.append("")
    return "\n".join(out)
